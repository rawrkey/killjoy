const PAGE_TITLES: Record<string, string> = {
  '/': 'Autonomous Command Center',
  '/judge': 'Judge Mode & Hackathon Audit',
  '/positions': 'Live Options Positions',
  '/market': 'Market Regime & Volatility Analysis',
  '/trades': 'Decision Receipts & Order Journal',
  '/reports': 'Autonomous Cycle Execution Reports',
  '/graveyard': 'Strategy Mortality & Graveyard',
  '/settings': 'Configuration & Connectivity',
};

export default function ClientShell({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();
  const title = PAGE_TITLES[pathname] || 'Autonomous Trading Terminal';
  const [marketOpen, setMarketOpen] = useState(false);
  const [etTime, setEtTime] = useState('');

  useEffect(() => {
    const updateTime = () => {
      const now = new Date();
      const et = new Date(now.toLocaleString('en-US', { timeZone: 'America/New_York' }));
      const day = et.getDay();
      const h = et.getHours();
      const m = et.getMinutes();
      const mins = h * 60 + m;
      setMarketOpen(day >= 1 && day <= 5 && mins >= 570 && mins < 960);
      setEtTime(
        et.toLocaleTimeString('en-US', {
          hour: '2-digit',
          minute: '2-digit',
          second: '2-digit',
          hour12: false,
        }) + ' ET'
      );
    };
    updateTime();
    const interval = setInterval(updateTime, 1000);
    return () => clearInterval(interval);
  }, []);

  return (
    <div className="app">
      <aside className="sidebar">
        <div className="sidebar-header">
          <div className="brand-row">
            <div className="logo">
              KILLJOY
              <span className="logo-badge">AI</span>
            </div>
          </div>
          <div className="sub">Adversarial Options Trading</div>
        </div>

        <nav className="sidebar-nav">
          {NAV_ITEMS.map((item) => (
            <a
              key={item.href}
              href={item.href}
              className={`nav-link ${pathname === item.href ? 'active' : ''}`}
            >
              <span className="nav-icon">{item.icon}</span>
              <span>{item.label}</span>
            </a>
          ))}
        </nav>

        <div className="sidebar-footer">
          <div className="status-row">
            <span>NYSE</span>
            <span className={`badge ${marketOpen ? 'badge-green' : 'badge-muted'}`}>
              {marketOpen ? 'OPEN' : 'CLOSED'}
            </span>
          </div>
          <div className="status-row" style={{ fontSize: 10, color: 'var(--text-dim)' }}>
            <span>{etTime || '9:30-16:00 ET'}</span>
            <span>v0.3.0</span>
          </div>
        </div>
      </aside>

      <main className="main">
        <header className="topbar">
          <div className="topbar-left">
            <h1 className="topbar-title">{title}</h1>
          </div>
          <div className="topbar-actions">
            <div className="status-dot-wrap">
              <span className="status-pulse" />
              <span className="status-dot on" />
            </div>
            <span className="badge badge-blue">PAPER TRADING</span>
            <span className="badge badge-purple">KILL AGENT ACTIVE</span>
            <span className="badge badge-green">8 RISK GATES</span>
          </div>
        </header>
        <div className="content">{children}</div>
      </main>
    </div>
  );
}
